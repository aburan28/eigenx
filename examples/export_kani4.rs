//! Export one Toy16 Eigen-Séta instance for Theta_dim4 `KaniEndoHalf`.
//!
//!   cargo run --release --example export_kani4 > research/kani4_sage/toy16_instance.sage
//!   THETA_DIM4=/tmp/Theta_dim4 sage research/kani4_sage/attack_toy16.sage
//!
//! The 3^F3-isogeny is evaluated here (fast). Sage only runs the dimension-4
//! chain on the exported torsion images.
use eigen_seta::cm::{mul_vartime, point_from_x};
use eigen_seta::cryptanalysis::kani4;
use eigen_seta::ct::ConstantTimeEq;
use eigen_seta::drbg::Drbg;
use eigen_seta::field::Field;
use eigen_seta::fp::FpConfig;
use eigen_seta::fp2::Fp2;
use eigen_seta::isog3::chain3;
use eigen_seta::kem::EigenSeta;
use eigen_seta::mont::{ladder3pt, ProjCurve, XPoint};
use eigen_seta::params::{ParamSet, Toy16};
use eigen_seta::scalar::Scalar;
use eigen_seta::weier::{WCurve, WPoint};
use num_bigint::BigUint;

type K = EigenSeta<Toy16, 4>;
type F = Fp2<<Toy16 as ParamSet<4>>::Cfg, 4>;

fn limbs(l: &[u64]) -> String {
    let mut b = Vec::new();
    for w in l {
        b.extend_from_slice(&w.to_le_bytes());
    }
    format!("{}", BigUint::from_bytes_le(&b))
}

fn fe(f: &F) -> String {
    format!(
        "({}, {})",
        limbs(&f.c0.to_canonical_limbs()),
        limbs(&f.c1.to_canonical_limbs())
    )
}

fn pt(p: &WPoint<F>) -> String {
    format!("({}, {})", fe(&p.x), fe(&p.y))
}

fn parse4(bytes: &[u8]) -> [F; 4] {
    let l = <F as Field>::byte_len();
    let mut out = [F::zero(); 4];
    for i in 0..4 {
        let (v, ok) = <F as Field>::from_bytes(&bytes[i * l..(i + 1) * l]);
        assert!(bool::from(ok));
        out[i] = v;
    }
    out
}

fn main() {
    let mut rng = Drbg::for_vector("kani4-export", 0);
    let (e_rob, a1, a2) = kani4::robert_params::<Toy16, 4, _>(&mut rng).expect("robert");
    let f = kani4::e_mask_for(e_rob);
    let (pk, _sk) = K::keygen(&mut rng);
    let [aa, xp, xq, _xpq] = parse4(&pk.bytes);
    let ea = WCurve::from_montgomery(aa);
    let p_full = point_from_x(&ea, xp).expect("P");
    let q_full = point_from_x(&ea, xq).expect("Q");
    let e = <Toy16 as ParamSet<4>>::E;
    assert!(e >= f);
    let shift = BigUint::from(1u32) << (e - f);
    let p1 = mul_vartime(&ea, &p_full, &shift);
    let q1 = mul_vartime(&ea, &q_full, &shift);

    let (pd, qd) = K::public_basis_3(&aa).expect("3-basis");
    let pqd = ea.sub(&pd, &qd);
    let pc = ProjCurve::from_affine(aa);
    let s = Scalar::from_u64(1, 2);
    let xk = ladder3pt(
        &XPoint::from_affine(pd.x),
        &XPoint::from_affine(qd.x),
        &XPoint::from_affine(pqd.x),
        &s,
        40,
        &pc,
    );
    let sum = ea.add(&p1, &q1);
    let mut imgs = [
        XPoint::from_affine(p1.x),
        XPoint::from_affine(q1.x),
        XPoint::from_affine(sum.x),
    ];
    let cod = chain3(&pc, &xk, <Toy16 as ParamSet<4>>::F3, &mut imgs);
    let ac = cod.affine_a();
    let ec = WCurve::from_montgomery(ac);
    let r0 = point_from_x(&ec, imgs[0].affine()).expect("phi(P)");
    let s0 = point_from_x(&ec, imgs[1].affine()).expect("phi(Q)");
    let t0 = point_from_x(&ec, imgs[2].affine()).expect("phi(P+Q)");
    // x-only evaluation loses y. Pick signs so φ(P)+φ(Q) has the same x as φ(P+Q).
    let mut r2 = r0;
    let mut s2 = s0;
    let mut matched = false;
    for sr in [false, true] {
        for ss in [false, true] {
            let rr = if sr { r0.neg() } else { r0 };
            let ss_ = if ss { s0.neg() } else { s0 };
            if bool::from(ec.add(&rr, &ss_).x.ct_eq(&t0.x)) {
                r2 = rr;
                s2 = ss_;
                matched = true;
            }
        }
    }
    assert!(matched, "no y-sign makes phi(P)+phi(Q) = ±phi(P+Q)");

    let p = limbs(&<Toy16 as ParamSet<4>>::Cfg::MODULUS);
    let q = BigUint::from(3u32).pow(<Toy16 as ParamSet<4>>::F3 as u32);
    println!("# generated by examples/export_kani4.rs — do not edit");
    println!("p = {p}");
    println!("q = {q}");
    println!("a1 = {a1}");
    println!("a2 = {a2}");
    println!("e = {e_rob}");
    println!("f = {f}");
    println!("A1 = {}", fe(&aa));
    println!("A2 = {}", fe(&ac));
    println!("P1 = {}", pt(&p1));
    println!("Q1 = {}", pt(&q1));
    println!("R2 = {}", pt(&r2));
    println!("S2 = {}", pt(&s2));
}
